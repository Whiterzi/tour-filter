const fromText=(text:string)=>Object.entries(places).filter(([country,names])=>names.some(name=>(country==="印度"?text.replaceAll("印度尼西亞","").replaceAll("印度洋",""):text).includes(name))).map(([country])=>country);
export function tourCountries(tour:Pick<Tour,"title"|"destination">):string[]{
 // A provided destination is stronger evidence than themed attractions in a title.
 const destination=(tour.destination||"").normalize("NFKC");
 const fromDestination=fromText(destination);
 if(fromDestination.length===1)return fromDestination;
 const fromTitle=fromText(tour.title.normalize("NFKC"));
 return fromTitle.length?fromTitle:fromDestination;
}
